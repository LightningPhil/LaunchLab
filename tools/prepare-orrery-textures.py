"""Package credited planet maps at up to three native-or-smaller resolutions.

python tools/prepare-orrery-textures.py CACHE_DIRECTORY [--download]
Requires Pillow. --download fetches the exact public sources in the manifest;
NASA GLB models contain their base-colour image in the first image buffer view.
Only deterministic resampling and WebP encoding are performed here.
"""
import hashlib
import json
import struct
import sys
import urllib.request
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
originals = Path(sys.argv[1])
originals.mkdir(parents=True, exist_ok=True)
destination = root / 'src/assets/orrery'
items = json.loads((root / 'tools/world-texture-sources.json').read_text())
lines = ["// Generated by tools/prepare-orrery-textures.py. Credits: docs/orrery-textures.md.",
         "export interface WorldMap { url: string; width: number }",
         "export const WORLD_MAPS: Record<string, readonly WorldMap[]> = {"]
for item in items:
    source_path = originals / item['source']
    if not source_path.exists() and '--download' in sys.argv:
        raw = urllib.request.urlopen(item['url'], timeout=90).read()
        if item['url'].endswith('.glb'):
            length = struct.unpack_from('<I', raw, 12)[0]
            model = json.loads(raw[20:20 + length])
            view = model['bufferViews'][model['images'][0]['bufferView']]
            offset = 28 + length + view.get('byteOffset', 0)
            raw = raw[offset:offset + view['byteLength']]
        source_path.write_bytes(raw)
    if hashlib.sha256(source_path.read_bytes()).hexdigest() != item['sha256']:
        raise ValueError(f"Source checksum changed: {source_path}")
    source = Image.open(source_path).convert('RGB')
    assert list(source.size) == item['nativeSize']
    lines.append(f"  {item['id']}: [")
    for width in item['widths']:
        assert width <= source.width, 'Do not invent detail by upscaling'
        filename = f"{item['id']}-{width}.webp"
        source.resize((width, width // 2), Image.Resampling.LANCZOS).save(
            destination / filename, quality=82 if width == 512 else 90, method=6)
        lines.append(f"    {{ width: {width}, url: new URL('./assets/orrery/{filename}', import.meta.url).href }},")
    lines.append('  ],')
    print(item['id'], item['widths'], flush=True)
lines.append('};')
(root / 'src/world-textures.ts').write_text('\n'.join(lines) + '\n')
